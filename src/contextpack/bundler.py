"""Context bundle renderer."""

from __future__ import annotations

from pathlib import Path

from .config import load_config
from .detector import detect_tools
from .models import BundleConfig, BundleResult, ProjectSummary, ScanResult
from .prompts import bugfix_prompt, default_prompt, docs_prompt, review_prompt, security_prompt
from .scanner import scan_repository
from .tokenizer import format_tokens
from .tree import build_tree
from .utils import get_project_name


def summarize_scan(scan: ScanResult) -> ProjectSummary:
    """Create a concise summary from a scan result."""

    notable = tuple(file.relative_path for file in scan.files[:12])
    return ProjectSummary(
        name=get_project_name(scan.root),
        project_type=scan.project_type,
        file_count=len(scan.files),
        token_estimate=scan.total_tokens,
        notable_files=notable,
        detected_tools=detect_tools(scan.root),
    )


def _select_prompt(style: str, summary: ProjectSummary) -> str:
    if style == "review":
        return review_prompt(summary)
    if style == "bugfix":
        return bugfix_prompt(summary)
    if style == "docs":
        return docs_prompt(summary)
    if style == "security":
        return security_prompt(summary)
    return default_prompt(summary)


def render_markdown_bundle(
    scan: ScanResult,
    config: BundleConfig,
    prompt_style: str = "default",
    max_files: int | None = None,
) -> str:
    """Render a Markdown context bundle."""

    summary = summarize_scan(scan)
    files = list(scan.files)
    if max_files is not None:
        files = files[:max_files]

    tree = build_tree(scan.root, config=config)
    prompt = _select_prompt(prompt_style, summary)

    lines: list[str] = []
    lines.append(f"# Context Pack: {summary.name}")
    lines.append("")
    lines.append("## AI Prompt")
    lines.append("")
    lines.append(prompt)
    lines.append("")
    lines.append("## Repository Summary")
    lines.append("")
    lines.append(f"- Project type: `{summary.project_type}`")
    lines.append(f"- Files included: `{len(files)}`")
    lines.append(f"- Estimated tokens: `{format_tokens(sum(item.token_estimate for item in files))}`")
    lines.append(f"- Raw size included: `{scan.total_bytes}` bytes")
    if summary.detected_tools:
        lines.append(f"- Detected tools: {', '.join(f'`{tool}`' for tool in summary.detected_tools)}")
    lines.append("")
    lines.append("## File Tree")
    lines.append("")
    lines.append("```text")
    lines.append(tree)
    lines.append("```")
    lines.append("")
    lines.append("## Included Files")
    lines.append("")
    for file in files:
        lines.append(f"### `{file.relative_path}`")
        lines.append("")
        lines.append(f"Size: `{file.size_bytes}` bytes | Tokens: `{file.token_estimate}`")
        lines.append("")
        lines.append(f"```{file.language}")
        lines.append(file.content.rstrip())
        lines.append("```")
        lines.append("")
    if scan.skipped:
        lines.append("## Skipped Files")
        lines.append("")
        for skipped in scan.skipped[:50]:
            lines.append(f"- `{skipped.relative_path}` - {skipped.reason}")
        if len(scan.skipped) > 50:
            lines.append(f"- ...and {len(scan.skipped) - 50} more skipped items")
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Generated by ContextPack.")
    return "\n".join(lines).rstrip() + "\n"


def build_bundle(
    root: Path,
    config: BundleConfig | None = None,
    prompt_style: str = "default",
    max_files: int | None = None,
) -> BundleResult:
    """Scan and render a repository context bundle."""

    config = config or load_config(root)
    scan = scan_repository(root, config=config)
    output = render_markdown_bundle(scan, config=config, prompt_style=prompt_style, max_files=max_files)
    files = scan.files if max_files is None else tuple(scan.files[:max_files])
    return BundleResult(
        root=scan.root,
        project_name=get_project_name(scan.root),
        project_type=scan.project_type,
        output=output,
        files=files,
        skipped=scan.skipped,
        total_tokens=sum(item.token_estimate for item in files),
        total_bytes=sum(item.size_bytes for item in files),
    )
